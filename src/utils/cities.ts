function toRad(d: number) { return (d * Math.PI) / 180; }

// מרחק אווירי בק"מ (נוסחת Haversine)
function haversineKm(a: [number, number], b: [number, number]): number {
  const R = 6371;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/** מרחק בק"מ בין שתי ערים; null אם אחת מהן לא ידועה במפה */
export function cityDistanceKm(cityA?: string, cityB?: string): number | null {
  if (!cityA || !cityB) return null;
  const a = CITY_COORDS[cityA.trim()];
  const b = CITY_COORDS[cityB.trim()];
  if (!a || !b) return null;
  return haversineKm(a, b);
}

/**
 * האם cityB נמצאת בטווח km מ-cityA.
 * אם אין קואורדינטות לאחת הערים — נופלים לבדיקת עיר זהה.
 */
export function isWithinKm(cityA?: string, cityB?: string, km = 30): boolean {
  const d = cityDistanceKm(cityA, cityB);
  if (d === null) {
    return !!cityA && !!cityB && cityA.trim() === cityB.trim();
  }
  return d <= km;
}
