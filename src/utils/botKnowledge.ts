// נרמול: הסרת ניקוד/סימנים, אחידות רווחים
function normalize(text: string): string {
  return (text || '')
    .toLowerCase()
    .replace(/[֑-ׇ]/g, '')     // ניקוד/טעמים
    .replace(/["'`׳״.,!?()\-–—:;]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function matchIntent(text: string, ctx: BotCtx): Intent | null {
  const q = normalize(text);
  if (!q) return null;

  let best: Intent | null = null;
  let bestScore = 0;

  for (const intent of INTENTS) {
    if (intent.roles && !intent.roles.includes(ctx.role)) continue;
    let score = 0;
    for (const kw of intent.keywords) {
      const k = normalize(kw);
      if (k && q.includes(k)) score += k.length; // התאמה ארוכה = ספציפית יותר
    }
    if (score > bestScore) { bestScore = score; best = intent; }
  }

  // סף מינימלי — מונע התאמות מקריות על מילה קצרה מדי
  return bestScore >= 3 ? best : null;
}

const FALLBACK = (ctx: BotCtx) => {
  const topics = ctx.role === 'restaurant'
    ? '- איך מפרסמים משמרת\n- כמה זה עולה לי\n- איך טוענים ארנק\n- איך בוחרים עובד\n- מדיניות ביטולים\n- תוכנית הכניסה (בוגרים)'
    : '- מתי אקבל את הכסף\n- מה העמלה שלי\n- איך מושכים כסף\n- מה זה "חשבונית לשכיר"\n- מדיניות ביטולים\n- רמות ודירוג';
  return `לא בטוח שהבנתי, אבל אני יודע לענות על:\n\n${topics}\n\nאפשר לנסח אחרת, או לפנות אלינו ב-support@staffly.com`;
};

/** התשובה הסופית לשאלה חופשית */
export function answerFor(text: string, ctx: BotCtx): string {
  const intent = matchIntent(text, ctx);
  return intent ? intent.answer(ctx) : FALLBACK(ctx);
}

/** שאלות מוצעות לפי תפקיד */
export function suggestionsFor(role: BotRole): string[] {
  if (role === 'restaurant') return ['כמה זה עולה לי?', 'איך מפרסמים משמרת?', 'איך טוענים ארנק?', 'מה קורה בביטול?'];
  if (role === 'admin')      return ['איך מחושבות העמלות?', 'מה זה "חשבונית לשכיר"?', 'מדיניות ביטולים', 'איך עובדות הרמות?'];
  return ['מתי אקבל את הכסף?', 'מה העמלה שלי?', 'איך מושכים כסף?', 'מה זה "חשבונית לשכיר"?'];
}
