const ils = (n: number) => `₪${Math.round(Number(n) || 0).toLocaleString()}`;

// ── עזרי הקשר לעובד ──
function workerLevelInfo(ctx: BotCtx) {
  const shifts = Number(ctx.profile?.CompletedShifts) || 0;
  const key = levelFromShifts(shifts).key;
  const rate = effectiveWorkerRate(key, false);
  const prog = nextLevelProgress(shifts);
  return { shifts, key, label: LEVEL_LABELS[key] || key, ratePct: (rate * 100).toFixed(1), prog };
}
